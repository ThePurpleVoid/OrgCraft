/** .agent-team/local.env holds one checkout's own settings (its role, its board folder) and must never be committed. */
export function ensureIgnored(root) {
  const gi = join(root, '.gitignore');
  const ignore = existsSync(gi) ? read(gi) : '';
  if (/^\/?\.agent-team\/local\.env$/m.test(ignore) || /^\*\.env$/m.test(ignore)) return false;
  writeFileSync(gi, `${ignore}${ignore && !ignore.endsWith('\n') ? '\n' : ''}\n# Agent Team Kit: this checkout's own role and board settings\n${LAYER}/local.env\n`);
  return true;
}

/** With AGENTS.md on, a role whose tool keeps no project memory may keep it in .agent-team/memory/: never committed. */
export function ensureMemoryIgnored(root) {
  const gi = join(root, '.gitignore');
  const ignore = existsSync(gi) ? read(gi) : '';
  if (/^\/?\.agent-team\/memory\/?$/m.test(ignore)) return false;
  writeFileSync(gi, `${ignore}${ignore && !ignore.endsWith('\n') ? '\n' : ''}\n# Agent Team Kit: role memory for agents without project memory (no board folder)\n${LAYER}/memory/\n`);
  return true;
}

export class UsageError extends Error {}

function readLock(root) {
  const p = join(root, LOCK);
  return existsSync(p) ? JSON.parse(read(p)) : { files: {} };
}

/**
 * Custom agents (.agent-team/roles/<slug>.md) that this kit now ships a role for, when the kit the team last synced
 * with did not (kit.lock.json "kitRoles"). Such an agent would silently replace the new kit role, so sync stops and
 * says how to fix it. A slug listed in team.json "replaces" is a deliberate replacement.
 */
export function shadowedRoles(root, project = loadProject(root)) {
  const lock = readLock(root);
  if (!Array.isArray(lock.kitRoles)) return [];
  const dir = join(root, LAYER, 'roles');
  const own = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.md') && !f.endsWith('.extend.md') && !f.startsWith('_') && f !== 'README.md').map((f) => f.slice(0, -3)) : [];
  const kit = new Set(kitRoleSlugs());
  return own.filter((s) => kit.has(s) && !lock.kitRoles.includes(s) && !project.replaces.includes(s));
}

const shadowMessage = (slug) => `${LAYER}/roles/${slug}.md: Agent Team Kit ${VERSION} adds a role called ${slug}, the same name as your custom agent. `
  + `Rename yours (move the file to a new slug and update "team-status.sh ${slug}" inside it), delete it to use the kit's, `
  + `or keep it as a replacement by adding "${slug}" to "replaces" in ${LAYER}/team.json.`;

export function sync(root, { quiet = false } = {}) {
  const log = (s) => { if (!quiet) console.log(s); };
  const shadowed = shadowedRoles(root);
  if (shadowed.length) { for (const s of shadowed) console.error(`error: ${shadowMessage(s)}`); console.error('sync stopped; nothing was written'); return 1; }
  const { files, project, roles, warnings } = build(root);
  const lock = readLock(root);
  for (const [rel, content] of files) {
    const p = join(root, rel);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
    if (!rel.endsWith('/lib.sh') && (rel.endsWith('.sh') || /^#!/.test(content))) chmodSync(p, 0o755);
  }
  for (const rel of Object.keys(lock.files ?? {})) {
    if (files.has(rel)) continue;
    const p = join(root, rel);
    if (!existsSync(p)) continue;
    // AGENTS.md may hold the repository's own text: take out only the kit's block.
    if (rel === AGENTS_MD) { const rest = withoutBlock(read(p)); if (rest === null) rmSync(p); else writeFileSync(p, rest); log(`removed the kit's block from ${rel}`); continue; }
    if (sha(read(p)) === lock.files[rel]) { rmSync(p); log(`removed ${rel}`); }
    else log(`kept ${rel}: it was generated before but has been edited; delete it yourself if it is no longer needed`);
  }
  if (ensureIgnored(root)) log(`added ${LAYER}/local.env to .gitignore (this checkout's own role and board settings)`);
  if (files.has(AGENTS_MD) && ensureMemoryIgnored(root)) log(`added ${LAYER}/memory/ to .gitignore (role memory for agents without their own)`);
  const settings = settingsChange(root, project);
  if (settings.changed) {
    mkdirSync(dirname(settings.path), { recursive: true });
    writeFileSync(settings.path, settings.after);
    log(`updated ${SETTINGS} (agent-team hooks${project.agentTeams ? ' and agent teams' : ''})`);
  }
  const next = { kit: project.kit, version: VERSION, kitRoles: kitRoleSlugs(), files: Object.fromEntries([...files].map(([k, v]) => [k, sha(v)]).sort()) };
  writeFileSync(join(root, LOCK), JSON.stringify(next, null, 2) + '\n');
  for (const w of warnings) log(`warning: ${w}`);
  const roster = checkRoster(roles.map((r) => parseBrief(r.slug, r.md)));
  for (const w of roster.warnings) log(`warning: ${w}`);
  for (const e of roster.errors) log(`error: ${e}`);
  log(`synced ${roles.length} roles and ${files.size} files from Agent Team Kit ${VERSION}`);
  return roster.errors.length ? 1 : 0;
}

export function check(root) {
  const problems = findProblems(root);
  for (const p of problems) console.log(p);
  console.log(problems.length ? `${problems.length} problems. Run scripts/agent-team/sync.sh and commit the result.` : `team is in sync with Agent Team Kit ${VERSION}`);
  return problems.length ? 1 : 0;
}

/** What check reports: generated files that are missing, edited or stale, settings without the kit's hooks, roster errors. */
export function findProblems(root) {
  const { files, roles, project } = build(root);
  const lock = readLock(root);
  const problems = [];
  for (const [rel, content] of files) {
    const p = join(root, rel);
    if (!existsSync(p)) problems.push(`missing: ${rel}`);
    else if (read(p) !== content) problems.push(`${sha(read(p)) === lock.files?.[rel] ? 'out of date' : 'edited by hand or out of date'}: ${rel}`);
  }
  for (const rel of Object.keys(lock.files ?? {})) if (!files.has(rel) && existsSync(join(root, rel)) && (rel !== AGENTS_MD || withoutBlock(read(join(root, rel))) !== read(join(root, rel)))) problems.push(`stale: ${rel}`);
  if (lock.version && lock.version !== VERSION) problems.push(`lock was written by kit ${lock.version}, this is ${VERSION}`);
  const roster = checkRoster(roles.map((r) => parseBrief(r.slug, r.md)));
  for (const e of roster.errors) problems.push(`roster: ${e}`);
  if (settingsChange(root, project).changed) problems.push(`out of date: ${SETTINGS} (the agent-team hooks)`);
  for (const s of shadowedRoles(root, project)) problems.push(`shadowed: ${shadowMessage(s)}`);
  return problems;
}

export function init(root, opts) {
  const teamFile = join(root, LAYER, 'team.json');
  if (existsSync(teamFile) && !opts.force) throw new UsageError(`${LAYER}/team.json already exists. Use "agent-team sync", or --force to start over.`);
  const project = opts.project ?? root.split('/').filter(Boolean).at(-1);
  const slug = project.toLowerCase().replace(/[^a-z0-9_-]+/g, '-').replace(/^-+|-+$/g, '');
  opts = { ...opts, timezone: initZone(opts.timezone) };
  if (opts.template) return initFromTemplate(root, opts, project, slug);
  presetRoles(opts.preset); // validates the preset name
  mkdirSync(join(root, LAYER, 'roles'), { recursive: true });
  const team = {
    kit: opts.kit ?? DEFAULT_KIT_SPEC,
    preset: opts.preset,
    include: [],
    exclude: [],
    values: { PROJECT_NAME: project, OWNER: opts.owner ?? 'the owner', TIMEZONE: opts.timezone, DIGEST_TIME: opts.digestTime ?? '08:00' },
    subagents: opts.subagents ?? false,
    hooks: true,
  };
  writeFileSync(teamFile, JSON.stringify(team, null, 2) + '\n');
  initExtras(root, slug, team.values, { ownership: true });
  const code = sync(root);
  console.log(`
Next:
  1. Edit ${DOCS}/ownership.md so the paths match this repository.
  2. Edit the gates and pools in ${LAYER}/config.sh.
  3. Paste ${DOCS}/project-instructions.md (below its line) into your Claude project's instructions, or into CLAUDE.md.
  4. Start the chief of staff: "Read ${DOCS}/roles/chief-of-staff.md and ${DOCS}/protocols.md."
  5. Commit .agent-team/, ${DOCS}/ and ${SCRIPTS}/. Add "${SCRIPTS}/sync.sh check" to CI.`);
  return code;
}

/** The files init writes once, besides team.json: config.sh, the roles README, ownership.md, the lane template, .gitignore. */
export function initExtras(root, slug, values, { ownership, quiet = false }) {
  const log = quiet ? () => {} : console.log;
  const once = (rel, content) => {
    const p = join(root, rel);
    if (existsSync(p)) { log(`kept ${rel}`); return; }
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
    log(`wrote ${rel}`);
  };
  once(`${LAYER}/config.sh`, read(join(KIT, 'templates/config.sh')).replace(/^AGENT_TEAM_PROJECT=.*$/m, `AGENT_TEAM_PROJECT="${slug}"`));
  once(`${LAYER}/roles/README.md`, read(join(KIT, 'templates/roles-README.md')));
  if (ownership) once(`${DOCS}/ownership.md`, fill(read(join(KIT, 'team/ownership.md')), values));
  once(`${DOCS}/lanes/_template.md`, read(join(KIT, 'team/lanes/_template.md')));
  const gi = join(root, '.gitignore');
  const ignore = existsSync(gi) ? read(gi) : '';
  if (!/^\.merge-gate\/$/m.test(ignore)) writeFileSync(gi, `${ignore}${ignore && !ignore.endsWith('\n') ? '\n' : ''}\n# Agent Team Kit merge gate logs\n.merge-gate/\n`);
}

/**
 * init's --timezone as an IANA zone: a common name ("Pacific", "UK") becomes its zone, an unknown one is refused, and
 * none given is this machine's zone (else UTC). Meetings and the scheduler need a zone Intl knows.
 */
function initZone(given) {
  if (given === undefined) {
    let here = ''; try { here = Intl.DateTimeFormat().resolvedOptions().timeZone; } catch { /* none */ }
    return toZone(here).from === 'iana' ? here : 'UTC';
  }
  const { zone, from } = toZone(given);
  if (!zone) throw new UsageError(`--timezone "${given}" is not a time zone: use an IANA name such as America/Los_Angeles, Europe/London or Asia/Kolkata`);
  if (from === 'alias') console.log(`Time zone "${given}" saved as ${zone}.`);
  return zone;
}

/** A template folder by id (the kit's) or by path. */
function templateFiles(idOrDir) {
  const kitOnes = loadTemplates(KIT);
  if (kitOnes[idOrDir]) return kitOnes[idOrDir];
  if (existsSync(join(idOrDir, 'template.json'))) return readTemplateDir(idOrDir);
  throw new UsageError(`no template "${idOrDir}" (templates: ${Object.keys(kitOnes).join(', ')})`);
}

/** init --template <id>: the team the Studio would make from the same template and answers (criterion 2). */
function initFromTemplate(root, opts, project, slug) {
  const files = templateFiles(opts.template);
  const kit = loadKit(KIT);
  const layer = templateLayer(files, kit, { project, owner: opts.owner ?? 'the owner', timezone: opts.timezone, kitVersion: VERSION, kitSpec: opts.kit ?? DEFAULT_KIT_SPEC });
  for (const line of writeLayer(root, layer)) console.log(line);
  initExtras(root, slug, JSON.parse(layer['team.json']).values, { ownership: !layer['ownership.json'] });
  const code = sync(root);
  console.log(`\nMade from the "${JSON.parse(files['template.json']).title}" template. Next: commit .agent-team/, ${DOCS}/ and ${SCRIPTS}/, and start the chief of staff: "Read ${DOCS}/roles/chief-of-staff.md and ${DOCS}/protocols.md."`);
  return code;
}

