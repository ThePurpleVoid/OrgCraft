#!/usr/bin/env node
// agent-team: use Agent Team Kit as a dependency. Your repository keeps only its project layer in .agent-team/;
// the kit generates the role briefs, protocols and scripts from it, pinned to one kit version.
//
//   agent-team init [--preset minimal|engineering|company] [--project "Name"] [--owner "Name"]
//                   [--timezone "UTC"] [--digest-time "08:00"] [--kit <npx spec>] [--subagents] [--force]
//   agent-team sync          regenerate docs/team/, scripts/agent-team/ (and .claude/agents/) from .agent-team/
//   agent-team check         exit 1 when a generated file is missing, edited by hand or out of date
//   agent-team roles         list the roles the project layer resolves to, and where each comes from
//   agent-team dashboard     open the live team dashboard (--port, --demo; "dashboard export --out dir" for a website)
//   agent-team version
//
// Run it with npx, without installing anything:
//   npx --yes github:PurpleGiragge/Agent-Team-Kit#v0.1.0 init --preset engineering --project "My App"
// After that, scripts/agent-team/sync.sh runs the kit version pinned in .agent-team/team.json.
import { createHash } from 'node:crypto';
import { chmodSync, existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseBrief } from '../tools/briefs.mjs';
import { check as checkRoster, tree } from '../tools/roster.mjs';
import { DEFAULT_MODELS, toSubagent } from '../tools/export-subagents.mjs';

export const KIT = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(KIT, 'package.json'), 'utf8'));
export const VERSION = pkg.version;
const DEFAULT_KIT_SPEC = `github:PurpleGiragge/Agent-Team-Kit#v${VERSION}`;

const LAYER = '.agent-team';
const DOCS = 'docs/team';
const SCRIPTS = 'scripts/agent-team';
const AGENTS = '.claude/agents';
const LOCK = `${LAYER}/kit.lock.json`;
const RUNTIME = ['lib.sh', 'team-status.sh', 'team-board.sh', 'merge-gate.sh', 'with-lock.sh', 'janitor.sh'];
const TOOLS = ['briefs.mjs', 'roster.mjs', 'export-subagents.mjs', 'roster-graph.mjs', 'board.mjs', 'dashboard.mjs'];
const DASHBOARD = ['index.html', 'app.js', 'app.css', 'config.js'];

const read = (p) => readFileSync(p, 'utf8');
const sha = (s) => createHash('sha256').update(s).digest('hex');
const mdMarker = () => `\n<!-- Generated by Agent Team Kit ${VERSION}. Do not edit: change .agent-team/ and run scripts/agent-team/sync.sh. -->\n`;
const shMarker = () => `# Generated by Agent Team Kit ${VERSION}. Do not edit: fixes go upstream, settings go in .agent-team/config.sh.`;

// ------------------------------------------------------------------------------------------------ project layer

export function loadProject(root) {
  const file = join(root, LAYER, 'team.json');
  if (!existsSync(file)) throw new UsageError(`No ${LAYER}/team.json here. Run "agent-team init" first.`);
  const team = JSON.parse(read(file));
  return {
    kit: team.kit ?? DEFAULT_KIT_SPEC,
    preset: team.preset ?? 'engineering',
    include: team.include ?? [],
    exclude: team.exclude ?? [],
    values: team.values ?? {},
    subagents: team.subagents ?? false,
    models: team.models ?? undefined,
  };
}

export function presetRoles(name) {
  const file = join(KIT, 'presets', `${name}.txt`);
  if (!existsSync(file)) throw new UsageError(`No preset "${name}" (have: ${readdirSync(join(KIT, 'presets')).map((f) => f.replace(/\.txt$/, '')).join(', ')})`);
  const slugs = read(file).split('\n').map((l) => l.replace(/#.*/, '').trim()).filter(Boolean);
  return slugs[0] === '*' ? kitRoleSlugs() : slugs;
}

const kitRoleSlugs = () => readdirSync(join(KIT, 'team/roles')).filter((f) => f.endsWith('.md') && !f.startsWith('_')).map((f) => f.slice(0, -3)).sort();

/** Splits a brief into its header (everything before the first "## ") and its sections, in order. */
function splitBrief(md) {
  const lines = md.replace(/\s+$/, '').split('\n');
  const header = [];
  const sections = [];
  for (const l of lines) {
    if (l.startsWith('## ')) sections.push({ heading: l, body: [] });
    else if (sections.length) sections.at(-1).body.push(l);
    else header.push(l);
  }
  return { header, sections };
}
const joinBrief = ({ header, sections }) =>
  [...header, ...sections.flatMap((s) => [s.heading, ...trimBlank(s.body), ''])].join('\n').replace(/\n{3,}/g, '\n\n').trim() + '\n';
const trimBlank = (a) => { const b = [...a]; while (b.length && !b[0].trim()) b.shift(); while (b.length && !b.at(-1).trim()) b.pop(); return b; };
const key = (heading) => heading.replace(/^##\s+/, '').replace(/\(.*?\)/g, '').trim().toLowerCase();

/**
 * Applies an extension to a brief:
 *   a "# Title" line renames the role;
 *   **Field:** value lines replace that header field (or are added to the header);
 *   "## Section" appends its body to the brief's section of the same name (added before the shared footer if new);
 *   "## Section (replace)" replaces that section's body.
 */
export function extendBrief(base, ext) {
  const b = splitBrief(base);
  const e = splitBrief(ext);
  for (const line of e.header) {
    if (/^#\s+/.test(line)) { // a title line renames the role
      const i = b.header.findIndex((l) => /^#\s+/.test(l));
      if (i >= 0) b.header[i] = line; else b.header.unshift(line);
      continue;
    }
    const m = /^\*\*([^*]+):\*\*/.exec(line);
    if (!m) continue;
    const i = b.header.findIndex((l) => l.startsWith(`**${m[1]}:**`));
    if (i >= 0) b.header[i] = line;
    else {
      const last = b.header.map((l, j) => (l.startsWith('**') ? j : -1)).filter((j) => j >= 0).at(-1) ?? 0;
      b.header.splice(last + 1, 0, line);
    }
  }
  for (const s of e.sections) {
    const replace = /\(replace\)\s*$/i.test(s.heading);
    const target = b.sections.find((x) => key(x.heading) === key(s.heading));
    if (target) target.body = replace ? trimBlank(s.body) : [...trimBlank(target.body), ...trimBlank(s.body)];
    else {
      const footer = b.sections.findIndex((x) => key(x.heading).startsWith('every thread'));
      const add = { heading: s.heading.replace(/\s*\(replace\)\s*$/i, ''), body: trimBlank(s.body) };
      b.sections.splice(footer >= 0 ? footer : b.sections.length, 0, add);
    }
  }
  return joinBrief(b);
}

/** Resolves the roles: the preset plus include, minus exclude, plus the project's own roles; then overrides and extensions. */
export function resolveRoles(root, project) {
  const dir = join(root, LAYER, 'roles');
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.md') && !f.startsWith('_') && f !== 'README.md') : [];
  const own = files.filter((f) => !f.endsWith('.extend.md')).map((f) => f.slice(0, -3));
  const extensions = files.filter((f) => f.endsWith('.extend.md')).map((f) => f.slice(0, -'.extend.md'.length));
  const kitSlugs = new Set(kitRoleSlugs());
  const wanted = new Set([...presetRoles(project.preset), ...project.include]);
  for (const x of project.exclude) wanted.delete(x);
  for (const s of own) wanted.add(s);
  const roles = [];
  const warnings = [];
  for (const slug of [...wanted].sort()) {
    let md;
    let source;
    if (own.includes(slug)) { md = read(join(dir, `${slug}.md`)); source = kitSlugs.has(slug) ? 'project (replaces kit)' : 'project'; }
    else if (kitSlugs.has(slug)) { md = read(join(KIT, 'team/roles', `${slug}.md`)); source = 'kit'; }
    else { warnings.push(`role "${slug}" is in include but neither the kit nor ${LAYER}/roles/ has it`); continue; }
    if (extensions.includes(slug)) { md = extendBrief(md, read(join(dir, `${slug}.extend.md`))); source += ' + extension'; }
    roles.push({ slug, md, source });
  }
  for (const x of extensions) if (!wanted.has(x)) warnings.push(`${LAYER}/roles/${x}.extend.md extends a role that is not installed`);
  // Point reporting lines at what is installed: a missing manager becomes the chief of staff, and direct-report
  // lists drop roles this project does not have.
  const installed = new Set(roles.map((r) => r.slug));
  for (const r of roles) r.md = fitToTeam(r.md, installed);
  return { roles, warnings };
}

export function fitToTeam(md, installed) {
  const brief = splitBrief(md);
  const top = installed.has('chief-of-staff') ? 'chief-of-staff' : null;
  brief.header = brief.header.map((l) => {
    const m = /^\*\*Reports to:\*\*\s*(\S+)/.exec(l);
    return m && m[1] !== 'owner' && !installed.has(m[1]) && top ? `**Reports to:** ${top} (${m[1]} is not part of this team)` : l;
  });
  const dr = brief.sections.find((x) => key(x.heading) === 'direct reports');
  if (dr) {
    const kept = dr.body.join(' ').split(',').map((x) => x.trim()).filter((x) => installed.has(x));
    if (kept.length) dr.body = [kept.join(', ')];
    else brief.sections.splice(brief.sections.indexOf(dr), 1);
  }
  return joinBrief(brief);
}

const fill = (text, values) => text.replace(/\{\{([A-Z0-9_]+)\}\}/g, (m, k) => (k in values ? String(values[k]) : m));

function withExtension(base, root, file, heading) {
  const p = join(root, LAYER, file);
  if (!existsSync(p)) return base;
  return `${base.trimEnd()}\n\n${heading}\n\n${read(p).trim()}\n`;
}

/** Every generated file, as relative path → content. */
export function build(root) {
  const project = loadProject(root);
  const values = { PROJECT_NAME: 'the product', OWNER: 'the owner', TIMEZONE: 'local time', DIGEST_TIME: '08:00', ...project.values };
  const { roles, warnings } = resolveRoles(root, project);
  values.ORG_TREE = '```\n' + tree(roles.map((r) => parseBrief(r.slug, fill(r.md, values)))) + '\n```';
  const out = new Map();
  const md = (path, text) => out.set(path, fill(text, values).trimEnd() + '\n' + mdMarker());

  md(`${DOCS}/README.md`, read(join(KIT, 'team/README.md')));
  md(`${DOCS}/protocols.md`, withExtension(read(join(KIT, 'team/protocols.md')), root, 'protocols.extend.md', `## ${values.PROJECT_NAME} rules`));
  md(`${DOCS}/project-instructions.md`, withExtension(read(join(KIT, 'team/project-instructions.md')), root, 'instructions.extend.md', `## ${values.PROJECT_NAME} rules`));
  md(`${DOCS}/role-template.md`, read(join(KIT, 'team/roles/_template.md')));
  for (const r of roles) md(`${DOCS}/roles/${r.slug}.md`, r.md);

  for (const f of RUNTIME) {
    const lines = read(join(KIT, 'scripts', f)).split('\n');
    lines.splice(1, 0, shMarker());
    out.set(`${SCRIPTS}/${f}`, lines.join('\n'));
  }
  // The marker goes after a hashbang line: Node only accepts #! as the very first line.
  const jsMarker = (text) => text.replace(/^(#![^\n]*\n)?/, (m) => `${m}// Generated by Agent Team Kit ${VERSION}. Do not edit.\n`);
  for (const f of TOOLS) out.set(`${SCRIPTS}/${f}`, jsMarker(read(join(KIT, 'tools', f))));
  for (const f of DASHBOARD) {
    const text = read(join(KIT, 'tools/dashboard', f));
    // config.js is the page's settings: generated with the defaults, which the local server needs.
    out.set(`${SCRIPTS}/dashboard/${f}`, f.endsWith('.html') ? text.replace('<!doctype html>\n', `<!doctype html>\n<!-- Generated by Agent Team Kit ${VERSION}. Do not edit. -->\n`)
      : f.endsWith('.css') ? `/* Generated by Agent Team Kit ${VERSION}. Do not edit. */\n${text}` : jsMarker(text));
  }
  out.set(`${SCRIPTS}/sync.sh`, read(join(KIT, 'templates/sync.sh')).replace('#!/usr/bin/env bash\n', `#!/usr/bin/env bash\n${shMarker()}\n`));

  if (project.subagents) {
    for (const r of roles) {
      const brief = parseBrief(r.slug, fill(r.md, values));
      if (brief.status === 'dormant' && project.subagents !== 'all') continue;
      out.set(`${AGENTS}/${r.slug}.md`, toSubagent(brief, { ...DEFAULT_MODELS, ...project.models }));
    }
  }
  return { files: out, project, roles, warnings };
}

// ------------------------------------------------------------------------------------------------ commands

class UsageError extends Error {}

function readLock(root) {
  const p = join(root, LOCK);
  return existsSync(p) ? JSON.parse(read(p)) : { files: {} };
}

export function sync(root, { quiet = false } = {}) {
  const { files, project, roles, warnings } = build(root);
  const lock = readLock(root);
  const log = (s) => { if (!quiet) console.log(s); };
  for (const [rel, content] of files) {
    const p = join(root, rel);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
    if (rel.endsWith('.sh') && !rel.endsWith('/lib.sh')) chmodSync(p, 0o755);
  }
  for (const rel of Object.keys(lock.files ?? {})) {
    if (files.has(rel)) continue;
    const p = join(root, rel);
    if (!existsSync(p)) continue;
    if (sha(read(p)) === lock.files[rel]) { rmSync(p); log(`removed ${rel}`); }
    else log(`kept ${rel}: it was generated before but has been edited; delete it yourself if it is no longer needed`);
  }
  const next = { kit: project.kit, version: VERSION, files: Object.fromEntries([...files].map(([k, v]) => [k, sha(v)]).sort()) };
  writeFileSync(join(root, LOCK), JSON.stringify(next, null, 2) + '\n');
  for (const w of warnings) log(`warning: ${w}`);
  const roster = checkRoster(roles.map((r) => parseBrief(r.slug, r.md)));
  for (const w of roster.warnings) log(`warning: ${w}`);
  for (const e of roster.errors) log(`error: ${e}`);
  log(`synced ${roles.length} roles and ${files.size} files from Agent Team Kit ${VERSION}`);
  return roster.errors.length ? 1 : 0;
}

export function check(root) {
  const { files, roles } = build(root);
  const lock = readLock(root);
  const problems = [];
  for (const [rel, content] of files) {
    const p = join(root, rel);
    if (!existsSync(p)) problems.push(`missing: ${rel}`);
    else if (read(p) !== content) problems.push(`${sha(read(p)) === lock.files?.[rel] ? 'out of date' : 'edited by hand or out of date'}: ${rel}`);
  }
  for (const rel of Object.keys(lock.files ?? {})) if (!files.has(rel) && existsSync(join(root, rel))) problems.push(`stale: ${rel}`);
  if (lock.version && lock.version !== VERSION) problems.push(`lock was written by kit ${lock.version}, this is ${VERSION}`);
  const roster = checkRoster(roles.map((r) => parseBrief(r.slug, r.md)));
  for (const e of roster.errors) problems.push(`roster: ${e}`);
  for (const p of problems) console.log(p);
  console.log(problems.length ? `${problems.length} problems. Run scripts/agent-team/sync.sh and commit the result.` : `team is in sync with Agent Team Kit ${VERSION}`);
  return problems.length ? 1 : 0;
}

export function init(root, opts) {
  const teamFile = join(root, LAYER, 'team.json');
  if (existsSync(teamFile) && !opts.force) throw new UsageError(`${LAYER}/team.json already exists. Use "agent-team sync", or --force to start over.`);
  presetRoles(opts.preset); // validates the preset name
  const project = opts.project ?? root.split('/').filter(Boolean).at(-1);
  const slug = project.toLowerCase().replace(/[^a-z0-9_-]+/g, '-').replace(/^-+|-+$/g, '');
  mkdirSync(join(root, LAYER, 'roles'), { recursive: true });
  const team = {
    kit: opts.kit ?? DEFAULT_KIT_SPEC,
    preset: opts.preset,
    include: [],
    exclude: [],
    values: { PROJECT_NAME: project, OWNER: opts.owner ?? 'the owner', TIMEZONE: opts.timezone ?? 'local time', DIGEST_TIME: opts.digestTime ?? '08:00' },
    subagents: opts.subagents ?? false,
  };
  writeFileSync(teamFile, JSON.stringify(team, null, 2) + '\n');
  const once = (rel, content) => {
    const p = join(root, rel);
    if (existsSync(p)) { console.log(`kept ${rel}`); return; }
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
    console.log(`wrote ${rel}`);
  };
  once(`${LAYER}/config.sh`, read(join(KIT, 'templates/config.sh')).replace(/^AGENT_TEAM_PROJECT=.*$/m, `AGENT_TEAM_PROJECT="${slug}"`));
  once(`${LAYER}/roles/README.md`, read(join(KIT, 'templates/roles-README.md')));
  once(`${DOCS}/ownership.md`, fill(read(join(KIT, 'team/ownership.md')), team.values));
  once(`${DOCS}/lanes/_template.md`, read(join(KIT, 'team/lanes/_template.md')));
  const gi = join(root, '.gitignore');
  const ignore = existsSync(gi) ? read(gi) : '';
  if (!/^\.merge-gate\/$/m.test(ignore)) writeFileSync(gi, `${ignore}${ignore && !ignore.endsWith('\n') ? '\n' : ''}\n# Agent Team Kit merge gate logs\n.merge-gate/\n`);
  const code = sync(root);
  console.log(`
Next:
  1. Edit ${DOCS}/ownership.md so the paths match this repository.
  2. Edit the gates and pools in ${LAYER}/config.sh.
  3. Paste ${DOCS}/project-instructions.md (below its line) into your Claude project's instructions, or into CLAUDE.md.
  4. Start the chief of staff: "Read ${DOCS}/roles/chief-of-staff.md and ${DOCS}/protocols.md."
  5. Commit .agent-team/, ${DOCS}/ and ${SCRIPTS}/. Add "${SCRIPTS}/sync.sh check" to CI.`);
  return code;
}

function listRoles(root) {
  const { roles, warnings } = resolveRoles(root, loadProject(root));
  for (const r of roles) console.log(`${r.slug.padEnd(28)} ${r.source}`);
  for (const w of warnings) console.log(`warning: ${w}`);
  return 0;
}

function parseArgs(argv) {
  const opts = { preset: 'engineering' };
  const names = { '--preset': 'preset', '--project': 'project', '--owner': 'owner', '--timezone': 'timezone', '--digest-time': 'digestTime', '--kit': 'kit', '--dir': 'dir' };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a in names) { if (argv[i + 1] === undefined) throw new UsageError(`${a} needs a value`); opts[names[a]] = argv[++i]; }
    else if (a === '--subagents') opts.subagents = true;
    else if (a === '--force') opts.force = true;
    else throw new UsageError(`unknown option ${a}`);
  }
  return opts;
}

export function main(argv) {
  const [cmd = 'help', ...rest] = argv;
  if (cmd === 'dashboard') return import('../tools/dashboard.mjs').then((m) => m.run(rest));
  try {
    const opts = parseArgs(rest);
    const root = opts.dir ?? process.cwd();
    if (opts.dir && !statSync(root, { throwIfNoEntry: false })?.isDirectory()) throw new UsageError(`${opts.dir} is not a folder`);
    switch (cmd) {
      case 'init': return init(root, opts);
      case 'sync': return sync(root);
      case 'check': return check(root);
      case 'roles': return listRoles(root);
      case 'version': case '--version': console.log(VERSION); return 0;
      case 'help': case '--help': case '-h':
        console.log(read(fileURLToPath(import.meta.url)).split('\n').slice(1).filter((l, i, a) => a.slice(0, i + 1).every((x) => x.startsWith('//'))).map((l) => l.replace(/^\/\/ ?/, '')).join('\n'));
        return 0;
      default: throw new UsageError(`unknown command "${cmd}" (init, sync, check, roles, dashboard, version)`);
    }
  } catch (e) {
    if (e instanceof UsageError) { console.error(`agent-team: ${e.message}`); return 64; }
    throw e;
  }
}

// npx runs the bin through a symlink, so compare real paths.
if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) Promise.resolve(main(process.argv.slice(2))).then((code) => { process.exitCode = code; });
