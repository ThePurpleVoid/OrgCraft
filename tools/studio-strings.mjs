#!/usr/bin/env node
// Builds the Studio's string table (apps/studio/public/strings.js) from the CPO's strings file, the one source for
// every word on a Now screen (plans/build/strings-now.md in the project files). Never edit strings.js by hand:
// the CPO changes the strings file, then
//
//   node tools/studio-strings.mjs <path to strings-now.md>
//
// Keyed tables ("| `key` | String |") become `key`. Tooltip tables ("| Word | Tooltip |") become `tip.<word>`, the
// word in lower case with dots for spaces and no punctuation ("Badge: Sends" → `tip.badge.sends`).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../apps/studio/public/strings.js');

export function parseStrings(md) {
  const out = {};
  let tips = false;
  for (const line of md.split('\n')) {
    if (/^\|\s*(Word|Item)\s*\|\s*Tooltip\s*\|/.test(line)) { tips = true; continue; }
    if (/^\|\s*Key\s*\|/.test(line)) { tips = false; continue; }
    if (/^#/.test(line)) tips = false;
    const cells = /^\|(.+)\|\s*$/.exec(line)?.[1].split(/(?<!\\)\|/).map((c) => c.trim());
    if (!cells || cells.length < 2 || /^-+$/.test(cells[0].replace(/:/g, ''))) continue;
    const [k, v] = cells;
    const key = /^`([^`]+)`$/.exec(k)?.[1];
    if (key && !tips) out[key] = v.replace(/\\\|/g, '|');
    else if (tips) out[`tip.${k.toLowerCase().replace(/[{}"“”,()]/g, '').replace(/[:/]/g, ' ').trim().replace(/\s+/g, '.')}`] = v;
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = process.argv[2];
  if (!src) { console.error('usage: node tools/studio-strings.mjs <strings-now.md>'); process.exit(2); }
  const table = parseStrings(readFileSync(src, 'utf8'));
  const body = Object.entries(table).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
  writeFileSync(OUT, `// Generated by tools/studio-strings.mjs from the CPO's strings file. Do not edit by hand.\nexport const EN = {\n${body}\n};\n`);
  console.log(`${Object.keys(table).length} strings → apps/studio/public/strings.js`);
}
