#!/usr/bin/env node
// Writes apps/studio/assets.json: the files a mounted Studio serves under /assets/<kit version>/<name> (S2). The
// handler only looks names up in this manifest, never joins a request path, so nothing else can be served.
//
//   node tools/studio-assets.mjs          write it
//   node tools/studio-assets.mjs check    exit 1 when it is out of date (CI)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const KIT = join(dirname(fileURLToPath(import.meta.url)), '..');
const TYPES = { '.js': 'text/javascript; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json; charset=utf-8', '.svg': 'image/svg+xml' };
// The page's own sign-in and account pages belong to the local and hosted Studio; a host's page is the sign-in.
const SKIP = /^(sign-in|account)\.|\.html$/;

export function manifest() {
  const files = {};
  for (const f of readdirSync(join(KIT, 'apps/studio/public')).sort()) {
    const ext = f.slice(f.lastIndexOf('.'));
    if (SKIP.test(f) || !TYPES[ext]) continue;
    files[f] = { path: `apps/studio/public/${f}`, type: TYPES[ext] };
  }
  files['team-model.mjs'] = { path: 'packages/team-model/index.mjs', type: TYPES['.mjs'] };
  files['model-prices.json'] = { path: 'packages/model-prices/prices.json', type: TYPES['.json'] };
  return `${JSON.stringify({ note: 'Generated by tools/studio-assets.mjs. Do not edit.', files }, null, 2)}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = join(KIT, 'apps/studio/assets.json');
  const text = manifest();
  if (process.argv[2] === 'check') {
    let now = ''; try { now = readFileSync(out, 'utf8'); } catch { /* missing */ }
    if (now !== text) { console.error('apps/studio/assets.json is out of date: run node tools/studio-assets.mjs'); process.exit(1); }
  } else writeFileSync(out, text);
}
