// The team model's data files (ownership.json, gates.json, resources.json) and validate.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { cpSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { build, KIT } from '../bin/agent-team.mjs';
import { compileLayer, importLayer, renderGates, setField, setSection, validate } from '../packages/team-model/index.mjs';
import { loadKit, readLayer, writeLayer } from '../packages/team-model/node.mjs';

const kit = loadKit();
const cli = join(KIT, 'bin/agent-team.mjs');
const tmp = (name) => mkdtempSync(join(tmpdir(), `team-model-${name}-`));

function dataTeam() {
  const root = tmp('data');
  execFileSync('git', ['init', '-q', root]);
  execFileSync(process.execPath, [cli, 'init', '--preset', 'minimal', '--project', 'Data', '--dir', root], { stdio: 'ignore' });
  const w = (f, v) => writeFileSync(join(root, '.agent-team', f), JSON.stringify(v, null, 2) + '\n');
  w('ownership.json', { rows: [{ path: 'apps/web/', writer: 'web-dev', notes: '' }, { path: 'api/', writer: 'backend-dev', notes: 'One migration author' }, { path: 'scripts/agent-team/', writer: 'Nobody: generated', notes: '' }] });
  w('gates.json', { all: ['web'], pools: { build: 1 }, targets: { web: [{ name: 'says hi', run: "echo 'hi there'" }, { name: 'locked step', run: 'true', pool: 'build' }] } });
  w('resources.json', { resources: [{ id: 'db', type: 'postgres', name: 'Main database', config: { database: 'app' }, secrets: ['DATABASE_URL'] }], bindings: [{ role: 'backend-dev', resource: 'db', permission: 'write' }, { role: 'qa-web', resource: 'db', permission: 'read' }] });
  execFileSync(process.execPath, [cli, 'sync', '--dir', root], { stdio: 'ignore' });
  return root;
}

test('ownership.json generates ownership.md with role titles the dashboard resolves', () => {
  const md = readFileSync(join(dataTeam(), 'docs/team/ownership.md'), 'utf8');
  assert.ok(md.includes('| `apps/web/` | Web dev |  |'));
  assert.ok(md.includes('| `api/` | Backend dev | One migration author |'));
  assert.match(md, /Generated by Agent Team Kit/);
});

test('gates.json generates gates.sh that merge-gate.sh runs', () => {
  const root = dataTeam();
  const out = execFileSync('bash', [join(root, 'scripts/agent-team/merge-gate.sh'), 'all'], { cwd: root, encoding: 'utf8', env: { ...process.env, AGENT_TEAM_HOME: tmp('home') } });
  assert.match(out, /PASS web: says hi/);
  assert.match(out, /PASS web: locked step/);
  const sh = renderGates({ targets: { x: [{ name: "it's", run: "echo 'a'" }] } });
  assert.ok(sh.includes(`run 'x: it'\\''s' bash -c 'echo '\\''a'\\'''`), sh);
});

test('resources.json adds a Systems table and each bound role learns its systems', () => {
  const root = dataTeam();
  assert.ok(readFileSync(join(root, 'docs/team/project-instructions.md'), 'utf8').includes('| Main database | postgres | database: app | `DATABASE_URL` | backend-dev (write), qa-web (read) |'));
  const brief = readFileSync(join(root, 'docs/team/roles/backend-dev.md'), 'utf8');
  assert.ok(brief.includes('## Systems\n- Main database (postgres): write. Secrets from the environment: `DATABASE_URL`.'));
  assert.ok(brief.indexOf('## Systems') < brief.indexOf('## Every thread'), 'Systems goes before the shared footer');
  assert.doesNotMatch(readFileSync(join(root, 'docs/team/roles/web-dev.md'), 'utf8'), /## Systems/);
});

test('round trip: a team with all three data files', () => {
  const root = dataTeam();
  const before = build(root).files;
  const copy = tmp('copy');
  cpSync(root, copy, { recursive: true });
  writeLayer(copy, compileLayer(JSON.parse(JSON.stringify(importLayer(readLayer(root), kit))), kit));
  const after = build(copy).files;
  assert.deepEqual([...after.keys()].sort(), [...before.keys()].sort());
  for (const [p, c] of before) assert.equal(after.get(p), c, p);
});

test('validate catches what would break a team', () => {
  const spec = importLayer(readLayer(dataTeam()), kit);
  assert.deepEqual(validate(spec, kit).filter((i) => i.level === 'error'), []);
  setField(spec, 'cto', 'Reports to', 'architect');
  setField(spec, 'architect', 'Reports to', 'cto');
  setField(spec, 'web-dev', 'Model', 'opus');
  spec.ownership.rows.push({ path: 'apps/web/', writer: 'qa-web' }, { path: 'docs/team/roles/', writer: 'docs-keeper' });
  spec.resources.bindings.push({ role: 'web-dev', resource: 'nope', permission: 'admin' });
  spec.resources.resources[0].secrets.push('postgres://app:hunter2@db/app');
  setSection(spec, 'docs-keeper', 'Tools', 'token sk-ant-api03-abcdefghijklmnopqrstuvwxyz');
  const errors = validate(spec, kit).filter((i) => i.level === 'error').map((i) => `${i.where}: ${i.message}`).join('\n');
  for (const want of [/loops back/, /model tier "opus"/, /apps\/web\/ has two writers/, /docs\/team\/roles\/ is generated/, /"nope", which is not a resource/, /permission "admin"/, /must be an environment variable name/, /roles\/docs-keeper: looks like it contains a secret/]) {
    assert.match(errors, want);
  }
});

test('the CLI validates', () => {
  assert.match(execFileSync(process.execPath, [cli, 'validate', '--dir', dataTeam()], { encoding: 'utf8' }), /0 errors/);
});
