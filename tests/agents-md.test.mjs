// Kit 0.15: an opt-in AGENTS.md for coding agents other than Claude Code (CPO story "Other coding agents", D42 to D48).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { KIT, build } from '../bin/agent-team.mjs';
import { importLayer, spliceBlock, validate, withoutBlock } from '../packages/team-model/index.mjs';
import { loadKit } from '../packages/team-model/node.mjs';

const kit = loadKit();
const cli = join(KIT, 'bin/agent-team.mjs');
const VENDORS = /\b(claude|anthropic|openai|codex|chatgpt|gpt-?\d*|gemini|google|copilot|github copilot|cursor|windsurf|aider|opencode|amp|devin|mistral|llama|deepseek|opus|sonnet|haiku|fable|o\d)\b/i;
const sh = (root, args, env = {}) => spawnSync(process.execPath, [cli, ...args], { cwd: root, encoding: 'utf8', env: { ...process.env, ...env } });

function team(targets, { preset = 'engineering', agentsMd } = {}) {
  const root = mkdtempSync(join(tmpdir(), 'agents-md-'));
  execFileSync('git', ['init', '-q'], { cwd: root });
  if (agentsMd !== undefined) writeFileSync(join(root, 'AGENTS.md'), agentsMd);
  assert.equal(sh(root, ['init', '--preset', preset, '--project', 'Acme', '--kit', 'file:' + KIT]).status, 0);
  if (targets) setTargets(root, targets);
  return root;
}
function setTargets(root, targets) {
  const f = join(root, '.agent-team/team.json');
  const t = JSON.parse(readFileSync(f, 'utf8'));
  if (targets === null) delete t.targets; else t.targets = targets;
  writeFileSync(f, JSON.stringify(t, null, 2) + '\n');
  return sh(root, ['sync']);
}

test('without agents-md nothing changes: no AGENTS.md, and the same files as a team that names only claude-code (criterion 3)', () => {
  const plain = team(null);
  assert.equal(existsSync(join(plain, 'AGENTS.md')), false);
  assert.doesNotMatch(readFileSync(join(plain, '.gitignore'), 'utf8'), /memory/);
  const named = team(['claude-code']);
  const a = build(plain).files;
  const b = build(named).files;
  assert.deepEqual([...a.keys()].sort(), [...b.keys()].sort());
  for (const [k, v] of a) if (!k.endsWith('team.json')) assert.equal(b.get(k), v, k);
  assert.ok(![...a.keys()].includes('AGENTS.md'));
});

test('with agents-md, sync writes AGENTS.md and check fails when it is stale or edited (criterion 1)', () => {
  const root = team(['claude-code', 'agents-md']);
  const text = readFileSync(join(root, 'AGENTS.md'), 'utf8');
  assert.match(text, /^<!-- agent-team:start: generated by OrgCraft /);
  assert.match(text, /<!-- agent-team:end -->\n$/);
  assert.equal(sh(root, ['check']).status, 0);
  writeFileSync(join(root, 'AGENTS.md'), text.replace('## Who you are', '## Who are you'));
  const r = sh(root, ['check']);
  assert.notEqual(r.status, 0);
  assert.match(r.stdout, /AGENTS\.md/);
});

test('AGENTS.md: tool-neutral words, how to find your role, the Node reporter; no vendor or model names (criterion 2)', () => {
  for (const preset of ['engineering', 'minimal', 'company']) {
    const root = team(['claude-code', 'agents-md'], { preset });
    const text = readFileSync(join(root, 'AGENTS.md'), 'utf8');
    const hit = text.split('\n').find((l) => VENDORS.test(l.replace(/https?:\/\/\S+/g, '')));
    assert.equal(hit, undefined, `${preset}: ${hit}`);
    assert.match(text, /AGENT_TEAM_ROLE/);
    assert.match(text, /docs\/team\/roles\/<role>\.md/);
    assert.match(text, /docs\/team\/protocols\.md/);
    assert.match(text, /node scripts\/agent-team\/report\.mjs <role> status working --task/);
    assert.doesNotMatch(text, /`scripts\/agent-team\/team-status\.sh`(?! takes the same arguments)/);
    for (const tier of ['deep', 'standard', 'routine', 'light']) assert.match(text, new RegExp(`\\*\\*${tier}\\*\\*`));
    assert.match(text, /## How work moves/, 'the project instructions are in it');
    assert.match(text, /\.agent-team\/memory\/<role>\.md/);
    assert.match(readFileSync(join(root, '.gitignore'), 'utf8'), /^\.agent-team\/memory\/$/m);
  }
  // A support team (core protocols only) gets the neutral instructions too.
  const support = mkdtempSync(join(tmpdir(), 'agents-md-support-'));
  execFileSync('git', ['init', '-q'], { cwd: support });
  assert.equal(sh(support, ['init', '--template', 'customer-support-team', '--project', 'Acme', '--kit', 'file:' + KIT]).status, 0);
  assert.equal(setTargets(support, ['claude-code', 'agents-md']).status, 0);
  const text = readFileSync(join(support, 'AGENTS.md'), 'utf8');
  assert.equal(text.split('\n').find((l) => VENDORS.test(l.replace(/https?:\/\/\S+/g, ''))), undefined);
  assert.match(text, /support-lead/);
});

test('a hand-written AGENTS.md keeps every line outside the markers, through syncs, edits and switching off (criterion 4)', () => {
  const own = '# Our agents\n\nUse pnpm, never npm.\nRun `make lint` before you push.\n';
  const root = team(['claude-code', 'agents-md'], { agentsMd: own });
  let text = readFileSync(join(root, 'AGENTS.md'), 'utf8');
  assert.ok(text.startsWith(own.trimEnd() + '\n\n<!-- agent-team:start'), text.slice(0, 200));
  // The repository edits its own part: sync keeps it, and check does not call it stale.
  writeFileSync(join(root, 'AGENTS.md'), text.replace('Use pnpm, never npm.', 'Use pnpm, never npm or yarn.') + '\n## After the kit\nKeep this too.\n');
  assert.equal(sh(root, ['check']).status, 0);
  assert.equal(sh(root, ['sync']).status, 0);
  text = readFileSync(join(root, 'AGENTS.md'), 'utf8');
  for (const line of ['# Our agents', 'Use pnpm, never npm or yarn.', 'Run `make lint` before you push.', '## After the kit', 'Keep this too.']) assert.ok(text.includes(line), line);
  assert.equal((text.match(/agent-team:start/g) ?? []).length, 1);
  // Switched off: the kit's block goes, the repository's text stays.
  assert.equal(setTargets(root, null).status, 0);
  text = readFileSync(join(root, 'AGENTS.md'), 'utf8');
  assert.doesNotMatch(text, /agent-team:start/);
  for (const line of ['# Our agents', 'Use pnpm, never npm or yarn.', 'Keep this too.']) assert.ok(text.includes(line), line);
  assert.equal(sh(root, ['check']).status, 0);
  // A file that was only the kit's block is removed when the target is switched off.
  const only = team(['claude-code', 'agents-md']);
  assert.equal(setTargets(only, ['claude-code']).status, 0);
  assert.equal(existsSync(join(only, 'AGENTS.md')), false);
});

test('the reporter commands in AGENTS.md work as written, without bash (D44)', () => {
  const root = team(['claude-code', 'agents-md']);
  const home = mkdtempSync(join(tmpdir(), 'agents-md-home-'));
  const text = readFileSync(join(root, 'AGENTS.md'), 'utf8');
  const lines = text.split('\n').filter((l) => l.startsWith('node scripts/agent-team/report.mjs')).map((l) => l.replace(/\s+#.*$/, ''));
  assert.ok(lines.length >= 7, lines.join('\n'));
  for (const line of lines) {
    const cmd = line.replace(/<role>/g, 'web-dev').replace(/<task>/g, 'Add a footer').replace(/<path>|<paths>/g, 'shots/a.png').replace(/"<[^>]+>"/g, '"note"').replace(/--to web-dev/, '--to qa-web');
    const args = [...cmd.matchAll(/"([^"]*)"|(\S+)/g)].map((m) => m[1] ?? m[2]).slice(1);
    const r = spawnSync(process.execPath, args, { cwd: root, encoding: 'utf8', env: { ...process.env, AGENT_TEAM_HOME: home, PATH: '/nonexistent', TEAM_REPORT_URL: '' } });
    assert.equal(r.status, 0, `${cmd}\n${r.stderr}`);
  }
  const events = readFileSync(join(home, 'acme', 'events.jsonl'), 'utf8').trim().split('\n').map((l) => JSON.parse(l));
  assert.ok(events.some((e) => e.role === 'web-dev' && e.kind === 'status' && e.status === 'working' && e.task === 'Add a footer'), JSON.stringify(events[0]));
});

test('an unknown target is refused by validate and by sync; the splice helpers', () => {
  const spec = importLayer({ 'team.json': JSON.stringify({ preset: 'minimal', targets: ['claude-code', 'vim'] }) }, kit);
  assert.ok(validate(spec, kit).some((i) => i.level === 'error' && /targets lists "vim"/.test(i.message)));
  const root = team(null, { preset: 'minimal' });
  const r = setTargets(root, ['claude-code', 'vim']);
  assert.notEqual(r.status, 0);
  assert.match(r.stderr + r.stdout, /targets lists "vim"/);
  const block = '<!-- agent-team:start: x -->\nkit\n<!-- agent-team:end -->';
  assert.equal(spliceBlock(null, block), `${block}\n`);
  assert.equal(spliceBlock('mine\n', block), `mine\n\n${block}\n`);
  assert.equal(spliceBlock(`a\n${block.replace('kit', 'old')}\nb\n`, block), `a\n${block}\nb\n`);
  assert.equal(withoutBlock(`${block}\n`), null);
  assert.equal(withoutBlock(`a\n\n${block}\n\nb\n`), 'a\n\nb\n');
});
