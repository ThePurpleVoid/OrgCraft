// Suggestions for the Studio's owned areas and checks, read from the repository: its folders and its build files.
// These are the repository connector's suggestions (ADR 0005); other connectors will offer their own.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { parseOwnership } from '../../tools/roster-graph.mjs';

/** Folder name patterns → the roles that usually own them, best first. The first one on the team wins. */
const RULES = [
  [/(^|\/)(apps\/)?(web|frontend|client|site|www|ui)\/$/, ['web-dev']],
  [/(^|\/)(apps\/)?(mobile|native|ios|android)\/$/, ['mobile-dev', 'ios-dev', 'android-dev']],
  [/(^|\/)(payments?|billing|checkout)\/$/, ['payments-engineer', 'backend-dev']],
  [/(^|\/)(ai|ml|prompts|llm|agents|evals)\/$/, ['ai-engineer', 'backend-dev']],
  [/(^|\/)(apps\/)?(api|server|backend|services?|supabase|functions|db|database|migrations|prisma)\/$/, ['backend-dev']],
  [/(^|\/)(e2e|playwright|cypress|tests?|__tests__|spec)\/$/, ['test-automation-engineer', 'qa-web']],
  [/(^|\/)(packages\/)?(shared|core|common|lib|libs|utils)\/$/, ['shared-core-dev', 'architect']],
  [/(^|\/)(design|tokens|theme|styles)\/$/, ['design-director', 'web-dev']],
  [/(^|\/)(docs|documentation)\/$/, ['docs-keeper']],
  [/(^|\/)(\.github|infra|deploy|terraform|k8s|helm|docker|ops)\/$/, ['infra-secrets-oncall', 'release-manager']],
];
/** Folders the team never owns: generated by sync, or the team itself. */
const SKIP = /^(\.git|node_modules|\.agent-team|docs\/team|scripts\/agent-team|\.claude|dist|build|coverage|vendor|\.next|\.turbo)\//;

/** Top-level folders, and the second level inside monorepo containers (apps/, packages/, services/), from file paths. */
export function foldersOf(files) {
  const out = new Set();
  for (const f of files) {
    const parts = f.split('/');
    if (parts.length < 2) continue;
    const top = `${parts[0]}/`;
    if (SKIP.test(top) || SKIP.test(`${parts[0]}/${parts[1]}/`)) continue;
    if (/^(apps|packages|services|libs|modules)\/$/.test(top) && parts.length > 2) out.add(`${top}${parts[1]}/`);
    else out.add(top);
  }
  return [...out].sort();
}

/** The same, for a checkout on disk. */
export function folders(root) {
  let files = [];
  try { files = execFileSync('git', ['-C', root, 'ls-files'], { encoding: 'utf8', maxBuffer: 64 << 20 }).split('\n').filter(Boolean); } catch { /* not a repository */ }
  if (!files.length) files = readdirSync(root).filter((f) => statSync(join(root, f)).isDirectory()).map((f) => `${f}/x`);
  return foldersOf(files);
}

/** Owned areas for folders no row covers yet: [{ path, writer, why }], from a folder list. */
export function suggestAreasFrom(list, rows, team) {
  const covered = (p) => rows.some((r) => p.startsWith(r.path.replace(/\*+$/, '')) || r.path.startsWith(p));
  const out = [];
  for (const path of list) {
    if (covered(path)) continue;
    const rule = RULES.find(([re]) => re.test(path));
    const writer = rule?.[1].find((s) => team.has(s));
    out.push({ path, writer: writer ?? '', why: writer ? `"${path}" usually belongs to ${writer}` : 'no role matched this folder; pick one' });
  }
  return out;
}

/** Owned areas for folders no row covers yet: [{ path, writer, why }]. `team` is the set of role slugs on the team. */
export const suggestAreas = (root, rows, team) => suggestAreasFrom(folders(root), rows, team);

/** Turns a hand-written ownership.md's text into rows, mapping writers by title to role slugs where it can. */
export function ownershipFromText(text, titles) {
  if (typeof text !== 'string') return [];
  const rows = [];
  for (const r of parseOwnership(text)) {
    const name = r.writer.replace(/[*`]/g, '').trim();
    const slug = titles.get(name.toLowerCase()) ?? (titles.has(name) ? name : null);
    for (const path of r.paths) rows.push({ path, writer: slug ?? name, notes: '' });
  }
  return rows;
}

/** Turns a hand-written docs/team/ownership.md into rows, mapping writers by title to role slugs where it can. */
export function ownershipFromMarkdown(root, titles) {
  const file = join(root, 'docs/team/ownership.md');
  return existsSync(file) ? ownershipFromText(readFileSync(file, 'utf8'), titles) : [];
}

/**
 * Checks from the build files at the repository root: [{ target, name, run, pool }]. `has(path)` says whether a root
 * file exists and `read(path)` gives its text (package.json only).
 */
export function suggestChecksFrom(has, read) {
  const out = [];
  if (has('package.json')) {
    let scripts = {};
    try { scripts = JSON.parse(read('package.json') ?? '{}').scripts ?? {}; } catch { /* unreadable */ }
    const pm = has('pnpm-lock.yaml') ? 'pnpm' : has('yarn.lock') ? 'yarn' : 'npm';
    const run = (s) => (pm === 'npm' ? (s === 'test' ? 'npm test' : `npm run ${s}`) : `${pm} ${s}`);
    for (const [s, pool] of [['lint', ''], ['typecheck', ''], ['type-check', ''], ['test', ''], ['build', 'build'], ['e2e', 'browser'], ['test:e2e', 'browser']]) {
      if (scripts[s]) out.push({ target: 'web', name: s, run: run(s), pool });
    }
  }
  if (has('Cargo.toml')) out.push({ target: 'rust', name: 'clippy', run: 'cargo clippy -- -D warnings', pool: 'build' }, { target: 'rust', name: 'test', run: 'cargo test', pool: 'build' });
  if (has('go.mod')) out.push({ target: 'go', name: 'vet', run: 'go vet ./...', pool: '' }, { target: 'go', name: 'test', run: 'go test ./...', pool: 'build' });
  if (has('pyproject.toml')) out.push({ target: 'python', name: 'test', run: 'python -m pytest', pool: '' });
  if (has('build.gradle') || has('build.gradle.kts')) out.push({ target: 'android', name: 'test', run: './gradlew test', pool: 'build' });
  if (has('Package.swift')) out.push({ target: 'ios', name: 'test', run: 'swift test', pool: 'build' });
  return out;
}

/** Checks from the build files of a checkout on disk. */
export const suggestChecks = (root) => suggestChecksFrom((p) => existsSync(join(root, p)), (p) => readFileSync(join(root, p), 'utf8'));
