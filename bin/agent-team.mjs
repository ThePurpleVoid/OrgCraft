// ------------------------------------------------------------------------------------------------ project layer

export function loadProject(root) {
  const file = join(root, LAYER, 'team.json');
  if (!existsSync(file)) throw new UsageError(`No ${LAYER}/team.json here. Run "agent-team init" first.`);
  const team = JSON.parse(read(file));
  return {
    kit: team.kit ?? DEFAULT_KIT_SPEC,
    preset: team.preset ?? 'engineering',
    include: team.include ?? [],
    exclude: team.exclude ?? [],
    values: team.values ?? {},
    subagents: team.subagents ?? false,
    models: team.models ?? undefined,
    dashboard: team.dashboard ?? undefined,
    hooks: team.hooks ?? false,
    agentTeams: team.agentTeams ?? false,
    replaces: team.replaces ?? [],
    packs: teamPacks(team),
    targets: teamTargets(team),
  };
}

export function presetRoles(name) {
  const file = join(KIT, 'presets', `${name}.txt`);
  if (!existsSync(file)) throw new UsageError(`No preset "${name}" (have: ${readdirSync(join(KIT, 'presets')).map((f) => f.replace(/\.txt$/, '')).join(', ')})`);
  const slugs = read(file).split('\n').map((l) => l.replace(/#.*/, '').trim()).filter(Boolean);
  return slugs[0] === '*' ? kitRoleSlugs() : slugs;
}

const kitRoleSlugs = () => readdirSync(join(KIT, 'team/roles')).filter((f) => f.endsWith('.md') && !f.startsWith('_')).map((f) => f.slice(0, -3)).sort();

/**
 * Applies an extension to a brief:
 *   a "# Title" line renames the role;
 *   **Field:** value lines replace that header field (or are added to the header);
 *   "## Section" appends its body to the brief's section of the same name (added before the shared footer if new);
 *   "## Section (replace)" replaces that section's body.
 */
export function extendBrief(base, ext) {
  return extendBriefText(base, ext);
}

/** Resolves the roles: the preset plus include, plus the project's own roles, minus exclude; then overrides and extensions. */
export function resolveRoles(root, project) {
  const dir = join(root, LAYER, 'roles');
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.md') && !f.startsWith('_') && f !== 'README.md') : [];
  const own = files.filter((f) => !f.endsWith('.extend.md')).map((f) => f.slice(0, -3));
  const extensions = files.filter((f) => f.endsWith('.extend.md')).map((f) => f.slice(0, -'.extend.md'.length));
  const kitSlugs = new Set(kitRoleSlugs());
  const wanted = new Set([...presetRoles(project.preset), ...project.include]);
  for (const x of project.exclude) wanted.delete(x);
  // A project role is installed unless exclude lists it (a custom agent switched off keeps its file).
  for (const s of own) if (!project.exclude.includes(s)) wanted.add(s);
  const roles = [];
  const warnings = [];
  for (const slug of [...wanted].sort()) {
    let md;
    let source;
    if (own.includes(slug)) { md = read(join(dir, `${slug}.md`)); source = kitSlugs.has(slug) ? 'project (replaces kit)' : 'project'; }
    else if (kitSlugs.has(slug)) { md = read(join(KIT, 'team/roles', `${slug}.md`)); source = 'kit'; }
    else { warnings.push(`role "${slug}" is in include but neither the kit nor ${LAYER}/roles/ has it`); continue; }
    if (extensions.includes(slug)) { md = extendBrief(md, read(join(dir, `${slug}.extend.md`))); source += ' + extension'; }
    roles.push({ slug, md, source });
  }
  for (const x of extensions) if (!wanted.has(x)) warnings.push(`${LAYER}/roles/${x}.extend.md extends a role that is not installed`);
  // Point reporting lines at what is installed: a missing manager becomes the chief of staff, and direct-report
  // lists drop roles this project does not have.
  const installed = new Set(roles.map((r) => r.slug));
  for (const r of roles) r.md = fitToTeam(r.md, installed);
  return { roles, warnings };
}

export { fitToTeam };

const fill = (text, values) => text.replace(/\{\{([A-Z0-9_]+)\}\}/g, (m, k) => (k in values ? String(values[k]) : m));

function withExtension(base, root, file, heading) {
  const p = join(root, LAYER, file);
  if (!existsSync(p)) return base;
  return `${base.trimEnd()}\n\n${heading}\n\n${read(p).trim()}\n`;
}

/** Every generated file, as relative path → content. */
export function build(root) {
  const project = loadProject(root);
  const values = { PROJECT_NAME: 'the product', OWNER: 'the owner', TIMEZONE: 'local time', DIGEST_TIME: '08:00', ...project.values };
  const data = (f) => { const p = join(root, LAYER, f); return existsSync(p) ? JSON.parse(read(p)) : undefined; };
  const ownershipData = data('ownership.json');
  const gatesData = data('gates.json');
  const resources = data('resources.json');
  const meetings = data('meetings.json');
  const resolved = resolveRoles(root, project);
  const roles = applyMeetings(applyBindings(resolved.roles, resources), meetings);
  const { warnings } = resolved;
  values.ORG_TREE = '```\n' + tree(roles.map((r) => parseBrief(r.slug, fill(r.md, values)))) + '\n```';
  const out = new Map();
  const md = (path, text) => out.set(path, fill(text, values).trimEnd() + '\n' + mdMarker());

  md(`${DOCS}/README.md`, read(join(KIT, 'team/README.md')));
  // The neutral core plus the team's packs (kit 0.13); a team.json without "packs" gets the engineering pack.
  const kit = loadKit(KIT);
  for (const p of project.packs) if (!kit.packs[p]) throw new UsageError(`team.json packs lists "${p}", which the kit does not have (packs: ${Object.keys(kit.packs).join(', ')})`);
  md(`${DOCS}/protocols.md`, withExtension(teamDoc(kit, 'protocols.md', project.packs), root, 'protocols.extend.md', `## ${values.PROJECT_NAME} rules`));
  const systems = resources ? renderSystems(resources) : '';
  const meetingsText = meetings ? renderMeetings(meetings, roles, { timezone: values.TIMEZONE }) : '';
  const instructions = withExtension(teamDoc(kit, 'project-instructions.md', project.packs), root, 'instructions.extend.md', `## ${values.PROJECT_NAME} rules`) + (systems ? `\n${systems}` : '') + (meetingsText ? `\n${meetingsText}` : '');
  md(`${DOCS}/project-instructions.md`, instructions);
  // AGENTS.md for other coding agents (targets "agents-md"): the kit's block, kept between markers so that the
  // repository's own text in the same file survives every sync.
  for (const t of project.targets) if (!TARGETS.includes(t)) throw new UsageError(`team.json targets lists "${t}"; the kit writes ${TARGETS.join(', ')}`);
  if (project.targets.includes('agents-md')) {
    const block = `<!-- agent-team:start: generated by Agent Team Kit ${VERSION}. Do not edit between these markers: change .agent-team/ and run scripts/agent-team/sync.sh. -->\n`
      + `${fill(read(join(KIT, 'team/agents-md.md')), values).trim()}\n\n${neutralInstructions(fill(instructions, values))}\n${AGENTS_END}`;
    out.set(AGENTS_MD, spliceBlock(existsSync(join(root, AGENTS_MD)) ? read(join(root, AGENTS_MD)) : null, block));
  }
  // With .agent-team/ownership.json, ownership.md is generated from it; without, it stays the repository's own file.
  if (ownershipData) md(`${DOCS}/ownership.md`, renderOwnership(ownershipData, roles));
  if (gatesData) { const g = renderGates(gatesData).split('\n'); g.splice(1, 0, shMarker()); out.set(`${SCRIPTS}/gates.sh`, g.join('\n')); }
  md(`${DOCS}/role-template.md`, roleTemplateFor(read(join(KIT, 'team/roles/_template.md')), project.packs));
  for (const r of roles) r.md = fitToPacks(r.md, project.packs);
  for (const r of roles) md(`${DOCS}/roles/${r.slug}.md`, r.md);

  for (const f of RUNTIME) {
    const lines = read(join(KIT, 'scripts', f)).split('\n');
    lines.splice(1, 0, shMarker());
    out.set(`${SCRIPTS}/${f}`, lines.join('\n'));
  }
  // The marker goes after a hashbang line: Node only accepts #! as the very first line.
  const jsMarker = (text) => text.replace(/^(#![^\n]*\n)?/, (m) => `${m}// Generated by Agent Team Kit ${VERSION}. Do not edit.\n`);
  for (const f of TOOLS) out.set(`${SCRIPTS}/${f}`, jsMarker(read(join(KIT, 'tools', f))));
  for (const f of DASHBOARD) {
    const text = read(join(KIT, 'tools/dashboard', f));
    // config.js is the page's settings: generated with the defaults, which the local server needs.
    out.set(`${SCRIPTS}/dashboard/${f}`, f.endsWith('.html') ? text.replace('<!doctype html>\n', `<!doctype html>\n<!-- Generated by Agent Team Kit ${VERSION}. Do not edit. -->\n`)
      : f.endsWith('.css') ? `/* Generated by Agent Team Kit ${VERSION}. Do not edit. */\n${text}` : jsMarker(text));
  }
  out.set(`${SCRIPTS}/sync.sh`, read(join(KIT, 'templates/sync.sh')).replace('#!/usr/bin/env bash\n', `#!/usr/bin/env bash\n${shMarker()}\n`));
  out.set(`${SCRIPTS}/sync.mjs`, jsMarker(read(join(KIT, 'templates/sync.mjs'))));

  // The dashboard for a website: the page code and this team's roster, written where the site's build picks them up.
  if (project.dashboard?.export) {
    const dir = project.dashboard.export.replace(/\/+$/, '');
    if (dir.startsWith('/') || dir.split('/').includes('..')) throw new UsageError('dashboard.export must be a folder inside the repository');
    const ownership = join(root, DOCS, 'ownership.md');
    const ownershipText = out.get(`${DOCS}/ownership.md`) ?? (existsSync(ownership) ? read(ownership) : '');
    const graph = graphFrom(roles.map((r) => parseBrief(r.slug, fill(r.md, values))), ownershipText);
    const roster = { project: values.PROJECT_NAME, repo: project.dashboard.repo ?? '', hosted: true, briefsPath: `${DOCS}/roles`,
      ...(project.dashboard.staleMinutes ? { staleMinutes: project.dashboard.staleMinutes } : {}), ...graph };
    out.set(`${dir}/roster.json`, JSON.stringify(roster, null, 1) + '\n');
    out.set(`${dir}/app.js`, jsMarker(read(join(KIT, 'tools/dashboard/app.js'))));
    out.set(`${dir}/app.css`, `/* Generated by Agent Team Kit ${VERSION}. Do not edit. */\n${read(join(KIT, 'tools/dashboard/app.css'))}`);
  }

  if (project.subagents || project.agentTeams) {
    for (const r of roles) {
      const brief = parseBrief(r.slug, fill(r.md, values));
      if (brief.status === 'dormant' && project.subagents !== 'all') continue;
      out.set(`${AGENTS}/${r.slug}.md`, toSubagent(brief, { ...DEFAULT_MODELS, ...project.models }));
    }
  }
  // Claude Code's agent teams: the roles as teammate types, and the prompts a lead uses to spawn them.
  if (project.agentTeams) {
    const briefs = roles.map((r) => parseBrief(r.slug, fill(r.md, values)));
    md(`${DOCS}/agent-teams.md`, agentTeamsGuide(graphFrom(briefs), values, project));
  }
  return { files: out, project, roles, warnings };
}

// ------------------------------------------------------------------------------------------------ Claude Code settings

const HOOK_EVENTS = ['SessionStart', 'UserPromptSubmit', 'PostToolUse', 'PreCompact', 'Stop', 'SubagentStart', 'SubagentStop', 'TeammateIdle', 'TaskCompleted', 'SessionEnd'];
const isKitHook = (h) => typeof h?.command === 'string' && h.command.includes(HOOK_SCRIPT);

/**
 * .claude/settings.json is the project's own file, so sync merges into it instead of owning it: the kit's hook
 * handlers (the ones that run scripts/agent-team/report.mjs) are replaced, everything else is kept.
 * Returns the new text, or null when there is nothing to write.
 */
export function mergeSettings(text, project) {
  let settings = {};
  if (text?.trim()) {
    try { settings = JSON.parse(text); } catch (e) { throw new UsageError(`${SETTINGS} is not valid JSON (${e.message})`); }
  }
  const hooks = settings.hooks ?? {};
  for (const ev of Object.keys(hooks)) {
    if (!Array.isArray(hooks[ev])) continue;
    hooks[ev] = hooks[ev].map((g) => ({ ...g, hooks: (g.hooks ?? []).filter((h) => !isKitHook(h)) })).filter((g) => g.hooks.length);
    if (!hooks[ev].length) delete hooks[ev];
  }
  if (project.hooks || project.agentTeams) {
    for (const ev of HOOK_EVENTS) {
      // The end of a turn or session reports before Claude Code moves on; everything else runs in the background.
      const sync = ev === 'Stop' || ev === 'SessionEnd';
      const handler = { type: 'command', command: `node "\${CLAUDE_PROJECT_DIR}/${HOOK_SCRIPT}" hook`, timeout: sync ? 8 : 15, ...(sync ? {} : { async: true }) };
      (hooks[ev] ??= []).push({ hooks: [handler] });
    }
  }
  if (Object.keys(hooks).length) settings.hooks = hooks; else delete settings.hooks;
  if (project.agentTeams) settings.env = { ...settings.env, CLAUDE_CODE_EXPERIMENTAL_AGENT_TEAMS: '1' };
  if (!text?.trim() && !Object.keys(settings).length) return null;
  return JSON.stringify(settings, null, 2) + '\n';
}

function settingsChange(root, project) {
  const p = join(root, SETTINGS);
  const before = existsSync(p) ? read(p) : null;
  const after = mergeSettings(before, project);
  return { path: p, before, after, changed: after !== null && after !== before };
}

function agentTeamsGuide(graph, values, project) {
  const live = graph.roles.filter((r) => !r.dormant);
  const bySlug = new Map(live.map((r) => [r.slug, r]));
  const leads = live.filter((r) => r.reports.some((s) => bySlug.has(s)));
  const lines = [
    `# Running ${values.PROJECT_NAME}'s team as a Claude Code agent team`,
    '',
    'Claude Code\'s [agent teams](https://code.claude.com/docs/en/agent-teams) run several sessions at once: a lead',
    'and teammates that share a task list and message each other. This team\'s roles are installed as teammate types',
    `in \`.claude/agents/\`, \`.claude/settings.json\` turns the feature on (\`CLAUDE_CODE_EXPERIMENTAL_AGENT_TEAMS\`),`,
    'and its hooks report every teammate to the board: working when it starts, done when it finishes a task, idle',
    'when it waits. Agent teams are experimental and need an interactive session (not `claude -p`), one team per session.',
    '',
    '## Start a team',
    '',
    '1. Open Claude Code in this repository as the lead role, so the board shows the lead too:',
    '',
    '   ```',
    `   AGENT_TEAM_ROLE=${leads[0]?.slug ?? 'chief-of-staff'} claude`,
    '   ```',
    '',
    '2. Ask for the team with the prompt for that lead (below). Name teammates by their role\'s slug: a teammate',
    '   spawned from the `backend-dev` agent type runs the backend developer\'s brief and reports as `backend-dev`.',
    '3. Each teammate still follows `docs/team/protocols.md`: it hands work on with a HANDOFF, files a BUG, and',
    '   asks the lead, never the owner. The lead synthesizes and reports to the owner.',
    '',
    'Threads in claude.ai projects and an agent team can run side by side: both write to the same board.',
    '',
    '## Prompts for each lead',
  ];
  for (const r of leads) {
    const mates = r.reports.filter((s) => bySlug.has(s));
    lines.push('', `### ${r.title} (\`${r.slug}\`)`, '', '```',
      `Create an agent team for <the job>. You are the ${r.title}: read docs/team/roles/${r.slug}.md and`,
      'docs/team/protocols.md first. Spawn only the teammates the job needs, each from its agent type and named',
      `after it: ${mates.join(', ')}. Give each teammate one task with acceptance criteria, require plan approval`,
      'before anyone edits code, and clean up the team when the job is done.', '```');
  }
  lines.push('', '## Limits', '',
    '- Teammates load the role briefs as subagent definitions: `skills` and `mcpServers` in a brief are not applied in-process.',
    '- There is no project-level team file: Claude Code keeps team state in `~/.claude/teams/`. Do not write it by hand.',
    `- Change who is on the team in \`.agent-team/team.json\` and run \`scripts/agent-team/sync.sh\`; turn this off with \`"agentTeams": false\`.`);
  return lines.join('\n') + '\n';
}

